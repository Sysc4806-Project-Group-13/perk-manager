-- user account database entry
CREATE TABLE users (

    -- uid
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- username for login
    username VARCHAR(100) NOT NULL UNIQUE,

    -- hashed password for account
    password_hash VARCHAR(255) NOT NULL,

    -- time of joining the site
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- table for many to many users and memberships relationship
CREATE TABLE user_memberships (

    -- UID and membership ID
    user_id BIGINT NOT NULL,
    membership_id BIGINT NOT NULL,

    -- Date the user joined the membership program
    added_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- ensure user cannot have duplicate memberships
    CONSTRAINT pk_user_memberships
      PRIMARY KEY (user_id, membership_id),

    -- if user is deleted, all of their memberships do as well
    CONSTRAINT fk_user_memberships_user
      FOREIGN KEY (user_id)
          REFERENCES users(id)
          ON DELETE CASCADE,

    -- if a membership is deleted, it is removed from user account
    CONSTRAINT fk_user_memberships_membership
      FOREIGN KEY (membership_id)
          REFERENCES memberships(id)
          ON DELETE CASCADE
);

-- better searches for memberships belonging to a user
CREATE INDEX idx_user_memberships_membership_id
    ON user_memberships(membership_id);
