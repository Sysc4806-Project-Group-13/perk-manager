
-- Membership programs
CREATE TABLE memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Name and description of membership
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
);

-- Perks offered by a membership
CREATE TABLE perks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Title and description of perk
    title VARCHAR(100) NOT NULL,
    description TEXT,

    -- Product or service the perk applies to
    product_name VARCHAR(100) NOT NULL,

    -- Type of benefit offered
    discount_type VARCHAR(100) NOT NULL,

    -- Numeric value of discount if offered
    discount_value DECIMAL(10, 2),

    -- Geographic restrictions
    geographic_area VARCHAR(100),

    -- Expiry date of perk
    expiry_date DATE,

    -- Membership corresponding to perk
    membership_id BIGINT NOT NULL,

    -- Foreign key relationship for perk and membership
    CONSTRAINT fk_perks_membership
       FOREIGN KEY (membership_id)
           REFERENCES memberships(id)
           ON DELETE CASCADE,

    -- Constrain the type of discount offered
    CONSTRAINT chk_perks_discount_type
       CHECK (discount_type IN (
            'PERCENTAGE',
            'FIXED_AMOUNT',
            'FREE_ITEM',
            'POINTS_REDEMPTION',
            'OTHER'
        )),

    -- Ensure that discount value is valid
    CONSTRAINT chk_perks_discount_value
       CHECK (discount_value IS NULL OR discount_value >= 0)
);

-- Allows for faster queries of perks by membership id
CREATE INDEX idx_perks_membership_id
    ON perks(membership_id);

-- Allows for faster queries of perks by product
CREATE INDEX idx_perks_product_name
    ON perks(product_name);

-- Allows for faster queries of perks by expiry date
CREATE INDEX idx_perks_expiry_date
    ON perks(expiry_date);
