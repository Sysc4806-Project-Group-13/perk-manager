package com.perkmanager.perk_manager;

import static org.junit.jupiter.api.Assertions.*;
import org.junit.jupiter.api.Test;
import com.perkmanager.perk_manager.model.DiscountType;
import com.perkmanager.perk_manager.model.Membership;
import com.perkmanager.perk_manager.model.Perk;
import com.perkmanager.perk_manager.repository.*;
import jakarta.persistence.EntityManager;
import jakarta.persistence.PersistenceContext;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;

@SpringBootTest
@Transactional
public class PerkRepositoryMappingTest {
    @Autowired
    private MembershipRepository membershipRepository;

    @Autowired
    private PerkRepository perkRepository;

    @PersistenceContext
    private EntityManager em;

    private void flushAndClear() {
        em.flush();
        em.clear();
    }

    private Membership newMembership(String name) {
        return membershipRepository.save(new Membership(name, "Test description"));
    }

    private Perk newPerk(String title, String product, Membership m, LocalDate expiry) {
        Perk p = new Perk(title, product, DiscountType.PERCENTAGE, m);
        p.setExpiryDate(expiry);
        return perkRepository.save(p);
    }

    // ---------- Round trips (Checks every column)----------
    @Test
    void membershipRoundTripKeepsAllColumns() {
        Membership saved = newMembership("ABC Test Card");
        flushAndClear();

        assertNotNull(saved.getId(), "identity id should be generated by the database");
        Membership loaded = membershipRepository.findById(saved.getId()).orElseThrow();
        assertEquals("ABC Test Card", loaded.getName());
        assertEquals("Test description", loaded.getDescription());
    }

    @Test
    void perkRoundTripKeepsEveryColumnAndTheMembership() {
        Membership m = newMembership("ABC Test Card");
        Perk p = new Perk("10% off movies", "ABC Movie Tickets", DiscountType.PERCENTAGE, m);
        p.setDescription("Valid on weekdays");
        p.setDiscountValue(new BigDecimal("10.50"));
        p.setGeographicArea("Ontario");
        p.setExpiryDate(LocalDate.now().plusDays(30));
        perkRepository.save(p);
        flushAndClear();

        Perk loaded = perkRepository.findById(p.getId()).orElseThrow();
        assertEquals("10% off movies", loaded.getTitle());
        assertEquals("Valid on weekdays", loaded.getDescription());
        assertEquals("ABC Movie Tickets", loaded.getProductName());
        assertEquals(DiscountType.PERCENTAGE, loaded.getDiscountType());
        assertEquals(0, new BigDecimal("10.50").compareTo(loaded.getDiscountValue()));
        assertEquals("Ontario", loaded.getGeographicArea());
        assertEquals(LocalDate.now().plusDays(30), loaded.getExpiryDate());
        assertEquals(m.getId(), loaded.getMembership().getId());
        assertEquals("ABC Test Card", loaded.getMembership().getName());
    }

    @Test
    void optionalColumnsMayBeNull() {
        Membership m = newMembership("ABC Test Card");
        Perk saved = newPerk("Free coffee", "ABC Coffee", m, null);
        flushAndClear();

        Perk loaded = perkRepository.findById(saved.getId()).orElseThrow();
        assertNull(loaded.getDescription());
        assertNull(loaded.getDiscountValue());
        assertNull(loaded.getGeographicArea());
        assertNull(loaded.getExpiryDate());
    }

    @Test
    void everyDiscountTypeCanBeSavedAndReloaded() {
        Membership m = newMembership("ABC Test Card");
        for (DiscountType type : DiscountType.values()) {
            perkRepository.save(new Perk("Perk " + type, "ABC Product", type, m));
        }
        flushAndClear();

        List<Perk> loaded = perkRepository.findByMembershipId(m.getId());
        assertEquals(DiscountType.values().length, loaded.size());
        assertEquals(1, perkRepository.findByDiscountType(DiscountType.FREE_ITEM).stream()
                .filter(p -> p.getMembership().getId().equals(m.getId())).count());
    }

    // ---------- Constraints (NOT NULL, UNIQUE, CHECK) ----------
    @Test
    void duplicateMembershipNameIsRejectedByTheDatabase() {
        // "Air Miles" is inserted by V2
        assertThrows(DataIntegrityViolationException.class,
                () -> membershipRepository.saveAndFlush(new Membership("Air Miles", "duplicate")));
    }

    @Test
    void negativeDiscountValueIsRejectedByTheDatabase() {
        Membership m = newMembership("ABC Test Card");
        Perk p = new Perk("Bad perk", "ABC Product", DiscountType.FIXED_AMOUNT, m);
        p.setDiscountValue(new BigDecimal("-5.00"));

        assertThrows(DataIntegrityViolationException.class, () -> perkRepository.saveAndFlush(p));
    }

    @Test
    void perkWithoutMembershipIsRejected() {
        assertThrows(RuntimeException.class, () -> perkRepository.saveAndFlush(
                new Perk("Orphan perk", "ABC Product", DiscountType.OTHER, null)));
    }

    @Test
    void deletingMembershipCascadesToPerksInTheDatabase() {
        Membership m = newMembership("ABC Test Card");
        Perk p = newPerk("Doomed perk", "ABC Product", m, null);
        flushAndClear();

        membershipRepository.deleteById(m.getId());
        flushAndClear();

        // V1 defines ON DELETE CASCADE, so the database removed the perk itself
        assertTrue(perkRepository.findById(p.getId()).isEmpty());
    }

    // ---------- Repository queries ----------
    @Test
    void findByMembershipIdReturnsOnlyThatMembershipsPerks() {
        Membership a = newMembership("ABC A");
        Membership b = newMembership("ABC B");
        newPerk("A1", "ABC P", a, null);
        newPerk("A2", "ABC P2", a, null);
        newPerk("B1", "ABC P", b, null);
        flushAndClear();

        List<Perk> result = perkRepository.findByMembershipId(a.getId());
        assertEquals(2, result.size());
        assertTrue(result.stream().allMatch(p -> p.getMembership().getId().equals(a.getId())));

        assertEquals(3, perkRepository.findByMembershipIdIn(List.of(a.getId(), b.getId())).size());
    }

    @Test
    void findActiveExcludesExpiredAndOrdersByExpiryWithNullsLast() {
        Membership m = newMembership("ABC Test Card");
        LocalDate today = LocalDate.now();
        newPerk("later", "ABC P", m, today.plusDays(90));
        newPerk("never", "ABC P", m, null);
        newPerk("soon", "ABC P", m, today.plusDays(5));
        newPerk("expired", "ABC P", m, today.minusDays(1));
        newPerk("today", "ABC P", m, today);
        flushAndClear();

        // Only this test's perks: the table also contains the V2 seed data
        List<String> titles = perkRepository.findActive(today).stream()
                .filter(p -> p.getMembership().getId().equals(m.getId()))
                .map(Perk::getTitle)
                .toList();

        assertEquals(List.of("today", "soon", "later", "never"), titles);
    }

    @Test
    void findActiveInAreaIncludesUnrestrictedPerksAndMatchingAreaOnly() {
        Membership m = newMembership("ABC Test Card");
        Perk anywhere = newPerk("anywhere", "ABC P", m, null);
        Perk ontario = newPerk("ontario", "ABC P", m, null);
        ontario.setGeographicArea("Ontario");
        Perk quebec = newPerk("quebec", "ABC P", m, null);
        quebec.setGeographicArea("Quebec");
        flushAndClear();

        List<String> titles = perkRepository.findActiveInArea(LocalDate.now(), "ONTARIO").stream()
                .filter(p -> p.getMembership().getId().equals(m.getId()))
                .map(Perk::getTitle)
                .sorted()
                .toList();

        assertEquals(List.of("anywhere", "ontario"), titles);
    }

    @Test
    void searchActiveIsCaseInsensitiveAndChecksAllSearchedColumns() {
        Membership m = newMembership("ABCcard Gold");
        LocalDate today = LocalDate.now();
        newPerk("Other", "ABCmovie Tickets", m, null);                    // product match
        Perk byTitle = newPerk("ABCmovie special", "Unrelated", m, null); // title match
        Perk byDesc = newPerk("Plain", "Unrelated", m, null);
        byDesc.setDescription("a ABCMOVIE night");                         // description match
        newPerk("Hidden", "Unrelated", m, null);                          // matches only via membership name
        newPerk("Expired ABCmovie", "ABCmovie", m, today.minusDays(1));    // matches but expired
        flushAndClear();

        assertEquals(3, perkRepository.searchActive("ABCMOVIE", today).size());
        assertEquals(4, perkRepository.searchActive("ABCcard", today).size()); // 4 active perks of this membership
        assertTrue(perkRepository.searchActive("no-such-keyword-xyz", today).isEmpty());
    }

    @Test
    void searchActiveForMembershipsOnlyReturnsThoseMemberships() {
        Membership mine = newMembership("ABC Mine");
        Membership other = newMembership("ABC Other");
        newPerk("ABCfind mine", "ABC P", mine, null);
        newPerk("ABCfind other", "ABC P", other, null);
        flushAndClear();

        List<Perk> result = perkRepository.searchActiveForMemberships(
                "ABCfind", LocalDate.now(), List.of(mine.getId()));

        assertEquals(1, result.size());
        assertEquals("ABCfind mine", result.get(0).getTitle());
    }

    // ---------- V2 seed data (verifies mapping against real stored rows) ----------
    @Test
    void seedDataFromV2LoadsThroughTheEntities() {
        Membership airMiles = membershipRepository.findByName("Air Miles").orElseThrow();
        List<Perk> perks = perkRepository.findByMembershipId(airMiles.getId());

        assertEquals(1, perks.size());
        Perk flight = perks.get(0);
        assertEquals("Free Domestic Flight", flight.getTitle());
        assertEquals("Domestic Flights", flight.getProductName());
        assertEquals(DiscountType.POINTS_REDEMPTION, flight.getDiscountType());
        assertEquals(0, new BigDecimal("10000").compareTo(flight.getDiscountValue()));
        assertEquals("Canada", flight.getGeographicArea());
        assertEquals(LocalDate.of(2027, 12, 31), flight.getExpiryDate());

        assertEquals(5, membershipRepository.count() - membershipRepository.findByNameContainingIgnoreCase("ABC").size());
    }
}
